func serveTemplate(name string, tmpl string, w io.Writer, data interface{}) {
	t, err := template.New(name).Parse(tmpl)
	if err != nil {
		panic(err)
	}
	if err := t.Execute(w, data); err != nil {
		panic(err)
	}
}

// getFileName generates a file name based on the existing files in the directory
// if name isn't taken leave it unchanged
// else change name to format "name(number).ext"
func getFileName(newFilename string, fileNamesInTargetDir []string) string {
	fileExt := filepath.Ext(newFilename)
	fileName := strings.TrimSuffix(newFilename, fileExt)
	number := 1
	i := 0
	for i < len(fileNamesInTargetDir) {
		if newFilename == fileNamesInTargetDir[i] {
			newFilename = fmt.Sprintf("%s(%v)%s", fileName, number, fileExt)
			number++
			i = 0
		}
		i++
	}
	return newFilename
}

// isHexString checks if a string consists only of hex characters and optional dashes
func isHexString(s string) bool {
	for _, c := range s {
		if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F') || c == '-') {
			return false
		}
	}
	return true
}

// sanitizeFilename replaces UUID-like filenames (generated by iOS Safari when
// uploading photos from the Photos library) with timestamp-based names
func sanitizeFilename(name string) string {
	ext := filepath.Ext(name)
	nameWithoutExt := strings.TrimSuffix(name, ext)

	// iOS Safari generates 32-character hex filenames for photos
	if len(nameWithoutExt) == 32 && isHexString(nameWithoutExt) {
		return "received_" + time.Now().Format("20060102_150405") + ext
	}

	// Also handle standard UUID format (36 chars with dashes)
	if len(nameWithoutExt) == 36 && isHexString(nameWithoutExt) {
		return "received_" + time.Now().Format("20060102_150405") + ext
	}

	return name
}

// readExifOrientation reads the EXIF orientation tag from a JPEG file.
// Returns 1 (Normal) if the file is not a JPEG or has no EXIF orientation.
func readExifOrientation(filePath string) int {
	data, err := os.ReadFile(filePath)
	if err != nil {
		return 1
	}

	// JPEG must start with SOI marker FF D8
	if len(data) < 10 || data[0] != 0xFF || data[1] != 0xD8 {
		return 1
	}

	i := 2
	for i < len(data)-4 {
		if data[i] != 0xFF {
			return 1
		}
		marker := data[i+1]

		// APP1 marker (EXIF data)
		if marker == 0xE1 {
			return parseExifApp1(data[i:])
		}

		// SOS marker (Start of Scan) - no more metadata after this
		if marker == 0xDA {
			return 1
		}

		if i+2 >= len(data) {
			return 1
		}
		segLen := int(binary.BigEndian.Uint16(data[i+2 : i+4]))
		i += 2 + segLen
	}
	return 1
}

// parseExifApp1 parses the APP1 segment to find the EXIF orientation tag.
func parseExifApp1(data []byte) int {
	// data[0:2] = FF E1 (marker)
	// data[2:4] = segment length
	// data[4:10] = "Exif\0\0"
	if len(data) < 14 || string(data[4:10]) != "Exif\x00\x00" {
		return 1
	}

	tiffData := data[10:]
	if len(tiffData) < 8 {
		return 1
	}

	// Determine byte order
	var bo binary.ByteOrder
	if tiffData[0] == 'I' && tiffData[1] == 'I' {
		bo = binary.LittleEndian
	} else if tiffData[0] == 'M' && tiffData[1] == 'M' {
		bo = binary.BigEndian
	} else {
		return 1
	}

	// Verify TIFF magic number
	if bo.Uint16(tiffData[2:4]) != 0x002A {
		return 1
	}

	// Get offset to first IFD
	ifdOffset := bo.Uint32(tiffData[4:8])
	if int(ifdOffset)+2 > len(tiffData) {
		return 1
	}

	// Read number of IFD entries
	numEntries := int(bo.Uint16(tiffData[ifdOffset : ifdOffset+2]))
	for e := 0; e < numEntries; e++ {
		entryOffset := int(ifdOffset) + 2 + e*12
		if entryOffset+12 > len(tiffData) {
			break
		}
		tag := bo.Uint16(tiffData[entryOffset : entryOffset+2])
		if tag == 0x0112 { // Orientation tag
			// Type should be SHORT (3), value is in the last 2 bytes
			return int(bo.Uint16(tiffData[entryOffset+8 : entryOffset+10]))
		}
	}
	return 1
}

// fixImageOrientation reads a JPEG file, checks its EXIF orientation,
// and if the image is rotated/flipped, physically rotates it and re-saves.
// This ensures correct display in viewers that ignore EXIF orientation
// (e.g., Windows File Explorer).
func fixImageOrientation(filePath string) error {
	orientation := readExifOrientation(filePath)
	if orientation <= 1 || orientation > 8 {
		return nil
	}

	f, err := os.Open(filePath)
	if err != nil {
		return err
	}
	defer f.Close()

	img, err := jpeg.Decode(f)
	if err != nil {
		return err
	}
	f.Close()

	rotated := rotateImage(img, orientation)
	if rotated == nil {
		return nil
	}

	out, err := os.Create(filePath)
	if err != nil {
		return err
	}
	defer out.Close()

	return jpeg.Encode(out, rotated, &jpeg.Options{Quality: 92})
}

// rotateImage rotates/flips an image based on EXIF orientation value.
func rotateImage(img image.Image, orientation int) image.Image {
	bounds := img.Bounds()
	w, h := bounds.Dx(), bounds.Dy()

	switch orientation {
	case 1:
		return img
	case 2:
		return flipHorizontal(img, w, h)
	case 3:
		return rotate180(img, w, h)
	case 4:
		return flipVertical(img, w, h)
	case 5:
		return transpose(img, w, h)
	case 6:
		return rotate90(img, w, h)
	case 7:
		return transverse(img, w, h)
	case 8:
		return rotate270(img, w, h)
	}
	return img
}

func rotate90(img image.Image, w, h int) image.Image {
	dst := image.NewRGBA(image.Rect(0, 0, h, w))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			dst.Set(h-y-1, x, img.At(x, y))
		}
	}
	return dst
}

func rotate180(img image.Image, w, h int) image.Image {
	dst := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			dst.Set(w-x-1, h-y-1, img.At(x, y))
		}
	}
	return dst
}

func rotate270(img image.Image, w, h int) image.Image {
	dst := image.NewRGBA(image.Rect(0, 0, h, w))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			dst.Set(y, w-x-1, img.At(x, y))
		}
	}
	return dst
}

